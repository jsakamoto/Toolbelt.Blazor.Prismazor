using System.Text;
using System.Text.RegularExpressions;

namespace Toolbelt.Blazor.Prismazor.Generator;

/// <summary>
/// Writes the C# source code of the languages in a <see cref="GrammarsFile"/>.
/// </summary>
internal class CodeEmitter(GrammarsFile file)
{
    // Hooks of PrismJS that are not about markup-templating, and the hand-written classes that port them.
    private static readonly Dictionary<string, string> PortedHooks = new()
    {
        ["graphql"] = "GraphqlHooks",
        ["jsx"] = "JsxHooks",
        ["markdown"] = "MarkdownHooks",
        ["naniscript"] = "NaniscriptHooks",
        ["tsx"] = "JsxHooks", // The hook of jsx works for tsx too.
        ["xquery"] = "XqueryHooks",
    };

    // Conditions in the hooks of markup-templating languages that the extractor cannot see. The code is not processed unless it matches.
    private static readonly Dictionary<string, string> TemplatingGuards = new()
    {
        ["php"] = @"<\?",
    };

    private readonly Dictionary<int, LanguageEntry> languageByRootGrammar = file.Languages.ToDictionary(l => l.Grammar);

    /// <summary>
    /// Returns whether the hooks of the given language are emitted.
    /// </summary>
    public bool HasHooks(LanguageEntry language) => language.Templating is not null || PortedHooks.ContainsKey(language.Id);

    private string Header =>
        $"""
        // <auto-generated/>
        // Generated by Toolbelt.Blazor.Prismazor.Generator from prismjs {file.PrismVersion}.
        // Prism is licensed under the MIT License. Copyright (c) 2012 Lea Verou.
        #nullable enable

        """;

    /// <summary>
    /// Returns the source code of the class that builds the grammar of the given language.
    /// </summary>
    /// <param name="language">The language to emit.</param>
    public string EmitLanguage(LanguageEntry language)
    {
        // Collect the grammars and patterns owned by this language. Another language's root is referenced, not copied.
        var grammarNames = new Dictionary<int, string>();
        var patternNames = new Dictionary<int, string>();
        var localGrammars = new List<int>();
        var localPatterns = new List<int>();

        void VisitGrammar(int id)
        {
            if (grammarNames.ContainsKey(id)) return;
            if (id != language.Grammar && this.languageByRootGrammar.TryGetValue(id, out var other))
            {
                grammarNames[id] = $"{other.ClassName}Language.Root";
                return;
            }
            grammarNames[id] = id == language.Grammar ? "Root" : $"g{localGrammars.Count}";
            localGrammars.Add(id);
            foreach (var token in file.Grammars[id].Tokens)
            {
                foreach (var patternId in token.Patterns)
                {
                    if (patternNames.ContainsKey(patternId)) continue;
                    patternNames[patternId] = $"p{localPatterns.Count}";
                    localPatterns.Add(patternId);
                    if (file.Patterns[patternId].Inside is { } inside) VisitGrammar(inside);
                }
            }
        }
        VisitGrammar(language.Grammar);
        if (language.Templating is { } templating) VisitGrammar(templating.Grammar);

        var className = $"{language.ClassName}Language";
        var sb = new StringBuilder();
        sb.Append(this.Header);
        sb.AppendLine("using System.Text.RegularExpressions;");
        if (this.HasHooks(language)) sb.AppendLine("using Toolbelt.Blazor.Prismazor.Hooks;");
        sb.AppendLine();
        sb.AppendLine("namespace Toolbelt.Blazor.Prismazor.Languages;");
        sb.AppendLine();
        sb.AppendLine($"internal static class {className}");
        sb.AppendLine("{");
        sb.AppendLine($"    internal static readonly Grammar Root = new({Literal(language.Id)});");
        sb.AppendLine();
        sb.AppendLine($"    static {className}()");
        sb.AppendLine("    {");

        foreach (var id in localGrammars.Where(id => id != language.Grammar))
        {
            sb.AppendLine($"        var {grammarNames[id]} = new Grammar();");
        }

        foreach (var id in localPatterns)
        {
            var node = file.Patterns[id];
            var (pattern, options) = JsRegexConverter.Convert(node.Source, node.Flags);
            sb.Append($"        var {patternNames[id]} = new GrammarPattern({Literal(pattern)}");
            if (options != RegexOptions.None) sb.Append($", options: {OptionsExpression(options)}");
            if (node.Lookbehind) sb.Append(", lookbehind: true");
            if (node.Greedy) sb.Append(", greedy: true");
            if (node.Alias is { Length: > 0 } alias) sb.Append($", alias: [{string.Join(", ", alias.Select(Literal))}]");
            if (node.Inside is { } inside) sb.Append($", inside: {grammarNames[inside]}");
            sb.AppendLine(");");
        }

        foreach (var id in localGrammars)
        {
            sb.AppendLine();
            sb.AppendLine($"        {grammarNames[id]}.Define([");
            foreach (var token in file.Grammars[id].Tokens)
            {
                sb.AppendLine($"            new({Literal(token.Name)}, [{string.Join(", ", token.Patterns.Select(p => patternNames[p]))}]),");
            }
            sb.AppendLine("        ]);");
        }

        if (language.Templating is { } t)
        {
            var (hookPattern, hookOptions) = JsRegexConverter.Convert(t.Source, t.Flags);
            sb.AppendLine();
            sb.Append($"        Root.Hooks = new TemplatingHooks(Root, {grammarNames[t.Grammar]}, {Literal(hookPattern)}");
            if (hookOptions != RegexOptions.None) sb.Append($", {OptionsExpression(hookOptions)}");
            if (TemplatingGuards.TryGetValue(language.Id, out var guard)) sb.Append($", guard: {Literal(guard)}");
            if (t.HasFilter) sb.Append($", filter: TemplatingFilters.{language.ClassName}");
            sb.AppendLine(");");
        }
        else if (PortedHooks.TryGetValue(language.Id, out var hooksClass))
        {
            sb.AppendLine();
            sb.AppendLine($"        Root.Hooks = new {hooksClass}();");
        }

        sb.AppendLine("    }");
        sb.AppendLine("}");
        return sb.ToString();
    }

    /// <summary>
    /// Returns the source code of the public <c>PrismazorLanguages</c> class.
    /// </summary>
    public string EmitPrismazorLanguages()
    {
        var sb = new StringBuilder();
        sb.Append(this.Header);
        sb.AppendLine("using Toolbelt.Blazor.Prismazor.Languages;");
        sb.AppendLine();
        sb.AppendLine("namespace Toolbelt.Blazor.Prismazor;");
        sb.AppendLine();
        sb.AppendLine("/// <summary>");
        sb.AppendLine("/// Provides the grammars of the supported languages.");
        sb.AppendLine("/// </summary>");
        sb.AppendLine("public static class PrismazorLanguages");
        sb.AppendLine("{");
        for (var i = 0; i < file.Languages.Length; i++)
        {
            var language = file.Languages[i];
            if (i > 0) sb.AppendLine();
            sb.AppendLine("    /// <summary>");
            sb.AppendLine($"    /// Gets the grammar of {System.Security.SecurityElement.Escape(language.Title)}.");
            sb.AppendLine("    /// </summary>");
            // A property per language keeps the trimmer able to remove the languages that an app does not use.
            sb.AppendLine($"    public static Grammar {language.ClassName} => {language.ClassName}Language.Root;");
        }
        sb.AppendLine("}");
        return sb.ToString();
    }

    private static string Literal(string value) => "@\"" + value.Replace("\"", "\"\"") + "\"";

    private static string OptionsExpression(RegexOptions options) =>
        string.Join(" | ", Enum.GetValues<RegexOptions>()
            .Where(o => o != RegexOptions.None && options.HasFlag(o))
            .Select(o => $"RegexOptions.{o}"));
}
